#! if else condition statement
/*
if else condtion works on the basis of true or false. If the condition is true then the code inside the if block will be executed otherwise it will be skipped and the code inside the else block will be executed.
*/

let age = 18;

if (age >= 18) {
    console.log("You are eligible to vote.");
} else {
    console.log("You are not eligible to vote.");
}
 // here only the condtion will check the age is greater than or equal to 18 or not. 
